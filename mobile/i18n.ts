// ── Hook ────────────────────────────────────────────────────────────────────
export function useT(): Strings {
    const lang = useVelaStore((s) => s.profile?.preferredLanguage ?? "en");
    return translations[lang] ?? translations.en;
}

// ── Non-hook accessor for use outside React components ──────────────────────
export function getT(lang?: string): Strings {
    return translations[lang ?? "en"] ?? translations.en;
}
